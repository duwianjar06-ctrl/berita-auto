import fs from 'node:fs';
import assert from 'node:assert/strict';
const read=p=>fs.readFileSync(new URL(`../${p}`,import.meta.url),'utf8');
const review=read('lib/instagram-review.js');
const route=read('app/api/admin/instagram/review/route.js');
const dashboard=read('app/admin-instagram/InstagramDashboard.jsx');
const settings=read('lib/instagram-automation.js');
const automation=read('lib/instagram-auto-upload.js');
const publishRoute=read('app/api/cron/social-publish/route.js');
assert.match(route,/status==='PUBLISHING'/,'delete must explicitly reject PUBLISHING');
assert.match(route,/status==='POSTED'/,'delete must preserve POSTED history');
assert.match(route,/queueIds/,'bulk failed delete must be supported');
assert.match(route,/review:removed:/,'delete must persist an exclusion tombstone');
assert.match(dashboard,/Aktifkan Auto Upload Instagram/,'toggle ON must confirm');
assert.match(dashboard,/Matikan Auto Upload/,'toggle OFF must confirm');
assert.match(dashboard,/api\/admin\/instagram\/automation/,'toggle must use server-side API');
assert.match(settings,/DEFAULT_AUTO_UPLOAD_ENABLED=false/,'Auto Upload default must be OFF');
assert.match(automation,/status==='READY'/,'auto worker must select READY only');
assert.match(automation,/autoUploadEnabled/,'auto worker must be gated by persistent setting');
assert.match(automation,/INSTAGRAM_AUTOMATION_SETTINGS_KEY/,'setting must be persisted server-side');
assert.match(publishRoute,/runInstagramAutoUpload/,'publishing must use a separate worker');
assert.match(publishRoute,/auto_upload_off/,'OFF must result in zero publishing');
assert.doesNotMatch(publishRoute,/runSocialCycle/,'Instagram auto worker must not re-enter generic social/news cycle');
assert.match(review,/removedKey\(id\)/,'preparation must honor removed tombstones');
console.log('instagram admin controls regression: PASS safe queue delete + persistent Auto Upload + isolated publishing worker');
