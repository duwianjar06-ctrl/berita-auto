import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const dashboard=await readFile(new URL('../app/admin-instagram/InstagramDashboard.jsx',import.meta.url),'utf8');
const status=await readFile(new URL('../app/api/admin/instagram/status/route.js',import.meta.url),'utf8');
const queueRoute=await readFile(new URL('../app/api/admin/instagram/queue/route.js',import.meta.url),'utf8');
assert.match(dashboard,/\/api\/admin\/instagram\/queue\?page=/);
assert.match(dashboard,/limit=10/);
assert.match(dashboard,/loading="lazy"/);
assert.match(dashboard,/decoding="async"/);
assert.match(dashboard,/width=\{120\}/);
assert.match(dashboard,/height=\{150\}/);
assert.doesNotMatch(queueRoute,/data:image\//);
assert.doesNotMatch(queueRoute,/Buffer\.from|toString\(['"]base64/);
assert.match(queueRoute,/mgetJson\(selected\.map/);
assert.match(queueRoute,/Math\.min\(20/);
assert.match(status,/const publishQueue=.*items:\[\]/);
assert.doesNotMatch(status,/return NextResponse\.json\(snapshot/);
assert.match(dashboard,/Hapus dari Antrean/);
assert.match(dashboard,/Lihat Berita/);
console.log('Instagram queue thumbnail regression: PASS bounded page, lazy thumbnails, no base64, separate queue endpoint, lightweight status payload, and preserved queue actions');
